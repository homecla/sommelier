import Foundation

/// App localization: source strings are Italian, `english` holds the translations.
/// The language is "system" (the Mac's preference, falling back to English), "en" or "it" (Settings).
enum Lang {
    static let settingKey = "appLanguage"

    /// Effective language: "en" or "it".
    static var current: String {
        let pref = UserDefaults.standard.string(forKey: settingKey) ?? "system"
        if pref == "en" || pref == "it" { return pref }
        for l in Locale.preferredLanguages {
            if l.hasPrefix("it") { return "it" }
            if l.hasPrefix("en") { return "en" }
        }
        return "en"
    }
}

/// Translates a UI string (key = Italian text, with %@ for values).
func L(_ key: String, _ args: String...) -> String {
    let format = Lang.current == "it" ? key : (english[key] ?? key)
    guard !args.isEmpty else { return format.replacingOccurrences(of: "%%", with: "%") }
    return String(format: format, arguments: args.map { $0 as NSString })
}

